CREATE TABLE ACCOUNT (
  ACCOUNT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USERNAME VARCHAR2(100) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR2(255) NOT NULL,
  ROLE_NAME VARCHAR2(20) NOT NULL,
  DISPLAY_NAME VARCHAR2(150) NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE CUSTOMER (
  CUSTOMER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ACCOUNT_ID NUMBER NOT NULL UNIQUE REFERENCES ACCOUNT(ACCOUNT_ID),
  FULL_NAME VARCHAR2(150) NOT NULL,
  PHONE VARCHAR2(30),
  EMAIL VARCHAR2(150),
  MEMBER_LEVEL VARCHAR2(50),
  POINTS NUMBER DEFAULT 0 NOT NULL
);

CREATE TABLE EMPLOYEE (
  EMPLOYEE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ACCOUNT_ID NUMBER NOT NULL UNIQUE REFERENCES ACCOUNT(ACCOUNT_ID),
  FULL_NAME VARCHAR2(150) NOT NULL,
  PHONE VARCHAR2(30),
  POSITION_NAME VARCHAR2(100)
);

CREATE TABLE COURT_TYPE (
  COURT_TYPE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COURT_TYPE_NAME VARCHAR2(100) NOT NULL UNIQUE,
  DESCRIPTION VARCHAR2(255)
);

CREATE TABLE COURT (
  COURT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COURT_NAME VARCHAR2(100) NOT NULL UNIQUE,
  COURT_TYPE_ID NUMBER NOT NULL REFERENCES COURT_TYPE(COURT_TYPE_ID),
  SURFACE_TYPE VARCHAR2(50),
  SPACE_TYPE VARCHAR2(50),
  PLAYER_COUNT NUMBER,
  STATUS VARCHAR2(30) DEFAULT 'AVAILABLE' NOT NULL,
  DESCRIPTION VARCHAR2(255),
  ADDRESS VARCHAR2(255)
);

CREATE TABLE PRICE_LIST (
  PRICE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COURT_TYPE_ID NUMBER NOT NULL UNIQUE REFERENCES COURT_TYPE(COURT_TYPE_ID),
  PRICE NUMBER(12, 2) NOT NULL
);

CREATE TABLE SERVICE_ITEM (
  SERVICE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SERVICE_NAME VARCHAR2(100) NOT NULL UNIQUE,
  UNIT_NAME VARCHAR2(50),
  PRICE NUMBER(12, 2) NOT NULL,
  STOCK_QUANTITY NUMBER DEFAULT 0 NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL
);

CREATE TABLE BOOKING (
  BOOKING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER(CUSTOMER_ID),
  COURT_ID NUMBER NOT NULL REFERENCES COURT(COURT_ID),
  EMPLOYEE_ID NUMBER REFERENCES EMPLOYEE(EMPLOYEE_ID),
  BOOKING_DATE DATE NOT NULL,
  SLOT_LABEL VARCHAR2(50) NOT NULL,
  STATUS VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
  TOTAL_AMOUNT NUMBER(12, 2) DEFAULT 0 NOT NULL,
  DEPOSIT_AMOUNT NUMBER(12, 2) DEFAULT 0 NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE PAYMENT (
  PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BOOKING_ID NUMBER NOT NULL UNIQUE REFERENCES BOOKING(BOOKING_ID),
  AMOUNT NUMBER(12, 2) NOT NULL,
  REFUND NUMBER(12, 2) DEFAULT 0 NOT NULL,
  METHOD_NAME VARCHAR2(50),
  PAYMENT_STATUS VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
  PAYMENT_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE COURT_RATING (
  RATING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER(CUSTOMER_ID),
  COURT_ID NUMBER NOT NULL REFERENCES COURT(COURT_ID),
  SCORE NUMBER(1) NOT NULL,
  COMMENT_TEXT VARCHAR2(255),
  RATING_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT COURT_RATING_SCORE_CHK CHECK (SCORE BETWEEN 1 AND 5),
  CONSTRAINT COURT_RATING_UNQ UNIQUE (CUSTOMER_ID, COURT_ID)
);

